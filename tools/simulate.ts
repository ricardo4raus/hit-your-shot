/**
 * Hit Your Shot pacing simulator. The bot in tools/sim/core.ts plays basketball through the real engine over several seeds; this file
 * writes docs/pacing-report.md with the milestone medians and the target verdicts.
 *
 * Run from the repository root:
 *     npm run simulate                      (12 seeds, 400 rounds each)
 *     npx tsx tools/simulate.ts --seeds 30 --rounds 600 --skill 4
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { defaultBalance, formatMoney } from '../src/engine';
import { fmtTime, median, medianMilestone, simulateCampaign, type CampaignResult, type Milestones } from './sim/core';
import { evaluateTargets } from './sim/targets';

function arg(name: string, fallback: number): number {
  const i = process.argv.indexOf(`--${name}`);
  if (i < 0) return fallback;
  const n = Number(process.argv[i + 1]);
  if (!Number.isFinite(n)) throw new Error(`--${name} needs a number`);
  return n;
}

const seeds = arg('seeds', 12);
const rounds = arg('rounds', 400);
const skillDeg = arg('skill', 4);
const balance = defaultBalance;

const started = Date.now();
const campaigns: CampaignResult[] = [];
for (let s = 1; s <= seeds; s++) {
  campaigns.push(simulateCampaign(balance, s, { rounds, skillDeg }));
  process.stdout.write(`seed ${s}/${seeds}\r`);
}
const elapsed = ((Date.now() - started) / 1000).toFixed(1);

const row = (cells: (string | number)[]) => `| ${cells.join(' | ')} |`;
const lines: string[] = [];
lines.push('# Pacing report');
lines.push('');
lines.push(`Generated by \`npm run simulate\` on ${new Date().toISOString().slice(0, 10)}: ${seeds} seeds, ${rounds} rounds each, bot aim error ±${skillDeg}°, ${elapsed} s.`);
lines.push('');
lines.push('## Targets (median over seeds)');
lines.push('');
lines.push(row(['Target', 'Result', 'Wanted', 'Met']));
lines.push(row(['---', '---', '---', '---']));
for (const t of evaluateTargets(campaigns)) lines.push(row([t.name, t.result, t.target, t.ok ? 'yes' : 'NO']));
lines.push('');
lines.push('## Milestones (median play time)');
lines.push('');
lines.push(row(['Milestone', 'Time']));
lines.push(row(['---', '---']));
const keys: (keyof Milestones)[] = ['firstUpgrade', 'firstBallSwap', 'limbs2', 'limbs3', 'limbs4', 'mastered', 'trophies10'];
for (const k of keys) lines.push(row([k, fmtTime(medianMilestone(campaigns, k))]));
lines.push('');
lines.push('## Income per round over time (median)');
lines.push('');
lines.push(row(['Round', 'Play time', 'Money', 'Hits / shots', 'Limbs', 'Ball', 'Levels acc/fire/inc']));
lines.push(row(['---', '---', '---', '---', '---', '---', '---']));
for (const i of [0, 1, 2, 4, 9, 19, 39, 59, 99, 149, 199, 299, 399]) {
  const at = campaigns.map((c) => c.rounds[i]).filter((r): r is NonNullable<typeof r> => !!r);
  if (at.length === 0) continue;
  const lv = (k: 'accuracy' | 'fireRate' | 'income') => Math.round(median(at.map((r) => r.levels[k])));
  lines.push(
    row([
      i + 1,
      fmtTime(median(at.map((r) => r.timeSec))),
      formatMoney(median(at.map((r) => r.money))),
      `${Math.round(median(at.map((r) => r.hits)))} / ${Math.round(median(at.map((r) => r.shots)))}`,
      Math.round(median(at.map((r) => r.limbs))),
      at[0]!.ball,
      `${lv('accuracy')}/${lv('fireRate')}/${lv('income')}`,
    ]),
  );
}
lines.push('');

const out = resolve(__dirname, '..', 'docs', 'pacing-report.md');
writeFileSync(out, lines.join('\n') + '\n');
console.log(lines.join('\n'));
console.log(`\nwritten: ${out}`);
